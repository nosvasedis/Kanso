#!/usr/bin/env node
/**
 * Rebuild CDN URLs from local content-hashed files (no re-download).
 * Use after changing iconCdnBase() / ICON_CDN_BASE.
 */
import fs from "node:fs/promises";
import path from "node:path";
import {
  ROOT,
  BADGE_IMAGE_FILES_DIR,
  BADGE_IMAGE_MANIFEST_PATH,
  cdnUrlForHash,
  hashIconBuffer,
} from "./icon-cdn.mjs";
import { CANONICAL_ICON_URLS } from "./canonical-icon-urls.mjs";

async function main() {
  const manifest = JSON.parse(await fs.readFile(BADGE_IMAGE_MANIFEST_PATH, "utf8"));
  const themes = manifest.themes;
  if (!themes) throw new Error("manifest missing themes");

  // Map old URL -> hash from sourceUrlToHash or by re-hashing files referenced in themes
  // Prefer: for each theme URL, extract hash16 from filename
  function hashFromUrl(url) {
    const m = String(url).match(/\/files\/([a-f0-9]{16})\.png/i);
    return m ? m[1] : null;
  }

  // Build full hash map from files on disk (filename is first 16 of sha256)
  const files = await fs.readdir(BADGE_IMAGE_FILES_DIR);
  const shortToFull = new Map();
  for (const file of files) {
    if (!file.endsWith(".png")) continue;
    const short = file.replace(/\.png$/i, "");
    const buf = await fs.readFile(path.join(BADGE_IMAGE_FILES_DIR, file));
    shortToFull.set(short, hashIconBuffer(buf));
  }

  function rewriteUrl(url) {
    const short = hashFromUrl(url);
    if (!short) return url;
    const full = shortToFull.get(short);
    if (!full) return url;
    return cdnUrlForHash(full);
  }

  const themeCdn = {};
  for (const [theme, idMap] of Object.entries(themes)) {
    themeCdn[theme] = {};
    for (const [id, url] of Object.entries(idMap)) {
      themeCdn[theme][id] = rewriteUrl(url);
    }
  }

  const baseUrls = {};
  for (const id of new Set([
    ...Object.keys(themeCdn.solid || {}),
    ...Object.keys(themeCdn.transparent || {}),
    ...Object.keys(themeCdn.mono || {}),
  ])) {
    baseUrls[id] =
      themeCdn.solid?.[id] ||
      themeCdn.transparent?.[id] ||
      themeCdn.mono?.[id];
  }

  let kingsizePrev = {};
  try {
    kingsizePrev = JSON.parse(
      await fs.readFile(path.join(ROOT, "badges", "kingsizew-icons.json"), "utf8")
    );
  } catch {
    /* optional */
  }
  const kingsizeNext = {};
  for (const id of Object.keys(kingsizePrev)) {
    kingsizeNext[id] =
      themeCdn.solid?.[id] ||
      themeCdn.transparent?.[id] ||
      themeCdn.mono?.[id] ||
      baseUrls[id];
  }

  const canonicalNext = {};
  for (const id of Object.keys(CANONICAL_ICON_URLS)) {
    if (themeCdn.solid?.[id]) canonicalNext[id] = themeCdn.solid[id];
  }

  manifest.themes = themeCdn;
  manifest.generatedAt = new Date().toISOString();
  manifest.cdnNote = "URLs rewritten via rewrite-icon-cdn-urls.mjs";

  await fs.writeFile(BADGE_IMAGE_MANIFEST_PATH, JSON.stringify(manifest, null, 2) + "\n");
  await fs.writeFile(
    path.join(ROOT, "badges", "icons-urls.json"),
    JSON.stringify(baseUrls, null, 2) + "\n"
  );
  await fs.writeFile(
    path.join(ROOT, "badges", "icons-urls-solid.json"),
    JSON.stringify(themeCdn.solid, null, 2) + "\n"
  );
  await fs.writeFile(
    path.join(ROOT, "badges", "icons-urls-transparent.json"),
    JSON.stringify(themeCdn.transparent, null, 2) + "\n"
  );
  await fs.writeFile(
    path.join(ROOT, "badges", "kingsizew-icons.json"),
    JSON.stringify(kingsizeNext, null, 2) + "\n"
  );
  await fs.writeFile(
    path.join(ROOT, "scripts", "canonical-icon-urls.mjs"),
    `/**
 * Stable CDN sources for Tiers / Quality / Release / Resolution badges.
 * Content-hashed files on nosvasedis/badge-images (GitHub raw).
 * Regenerated by scripts/materialize-badge-images.mjs / rewrite-icon-cdn-urls.mjs
 */
export const CANONICAL_ICON_URLS = ${JSON.stringify(canonicalNext, null, 2)};
`
  );

  console.log(
    `rewrite-icon-cdn-urls: solid=${Object.keys(themeCdn.solid || {}).length} sample=${Object.values(themeCdn.solid || {})[0]}`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
