/** Reproducible local build. Never uploads or modifies an application. */
import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';
import { buildPresetFormatter, MIN_AIOSTREAMS_VERSION } from './preset-formatter.mjs';
import { buildPresetBadges } from './preset-badges.mjs';
import { ROOT, BADGE_IMAGE_FILES_DIR, hashIconBuffer, iconFileName, cdnUrlForHash } from './icon-cdn.mjs';
const escape=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
export async function buildPresets(){
 await fs.mkdir(BADGE_IMAGE_FILES_DIR,{recursive:true});
 const generatedAt=new Date().toISOString();
 const manifest={generatedAt,brand:'Kanso',version:2,minimumAIOStreams:MIN_AIOSTREAMS_VERSION,themes:{},presets:{}};
 const cache=new Map();
 const formatters=Object.fromEntries(['compact','detailed'].map(p=>[p,buildPresetFormatter(p)]));
 for(const preset of ['compact','detailed']){
   const formatter=formatters[preset];
   const suffix=preset==='compact'?'':'-detailed';
   await fs.writeFile(path.join(ROOT,`formatter${suffix}.json`),JSON.stringify(formatter,null,2)+'\n');
   for(const field of ['name','description'])await fs.writeFile(path.join(ROOT,`formatter${suffix}-export-${field}.txt`),formatter[field]+'\n');
   manifest.presets[preset]={formatter:`formatter${suffix}.json`,lengths:{name:formatter.name.length,description:formatter.description.length},packs:{}};
   for(const theme of ['solid','transparent','mono']){
     const pack=buildPresetBadges(theme,preset);
     const iconMap={};
     for(const f of pack.filters){
       const key=f.label+'|'+f.textColor;
       if(!cache.has(key)){
         // Measure the actual renderer's glyph width, including wide letters.
         const measured=await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="100"><text x="10" y="70" font-family="Arial,Helvetica,sans-serif" font-size="56" font-weight="700" fill="white">${escape(f.label)}</text></svg>`)).trim().toBuffer({resolveWithObject:true});
         const font=measured.info.width>432?Math.floor(56*432/measured.info.width):56;
         const width=Math.min(460,Math.max(120,Math.ceil(measured.info.width*font/56)+28));
         const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="80"><text x="${width/2}" y="59" text-anchor="middle" font-family="Arial,Helvetica,sans-serif" font-size="${font}" font-weight="700" fill="${f.textColor}">${escape(f.label)}</text></svg>`;
         const buffer=await sharp(Buffer.from(svg)).png().toBuffer();
         const hash=hashIconBuffer(buffer);
         await fs.writeFile(path.join(BADGE_IMAGE_FILES_DIR,iconFileName(hash)),buffer);
         cache.set(key,cdnUrlForHash(hash));
       }
       f.imageURL=cache.get(key);iconMap[f.id]=f.imageURL;delete f.label;
     }
     const filename=`kanso-${theme}${suffix}.json`;
     await fs.writeFile(path.join(ROOT,filename),JSON.stringify(pack,null,2)+'\n');
     manifest.presets[preset].packs[theme]=filename;
     manifest.themes[theme+suffix]=iconMap;
     if(preset==='compact')await fs.writeFile(path.join(ROOT,'badges',theme==='solid'?'icons-urls-solid.json':theme==='transparent'?'icons-urls-transparent.json':'icons-urls-mono.json'),JSON.stringify(iconMap,null,2)+'\n');
   }
 }
 manifest.uniqueHashes=cache.size;
 await fs.writeFile(path.join(ROOT,'badges/badge-images/manifest.json'),JSON.stringify(manifest,null,2)+'\n');
 await fs.writeFile(path.join(ROOT,'badges/icons-urls.json'),JSON.stringify(manifest.themes.solid,null,2)+'\n');
 await fs.writeFile(path.join(ROOT,'scripts/canonical-icon-urls.mjs'),'/** Generated by build-presets.mjs. */\nexport const CANONICAL_ICON_URLS = '+JSON.stringify(manifest.themes.solid,null,2)+';\n');
 console.log(`Built Compact + Detailed, three skins, ${cache.size} content-addressed PNGs.`);
 for(const [preset,p] of Object.entries(manifest.presets))console.log(`${preset}: templates ${p.lengths.name}/${p.lengths.description} characters`);
 return manifest;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href)await buildPresets();
